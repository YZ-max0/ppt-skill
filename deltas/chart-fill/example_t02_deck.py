def _assert_clean(path: str) -> None:
    """产物不得残留：T-03 示例品牌字 / 未填占位符。"""
    with open(path, encoding="utf-8") as f:
        svg = f.read()
    leaks = [w for w in ("知识库", ">KB<", "信息化建设部") if w in svg]
    if leaks:
        raise AssertionError(f"{path}: 残留示例内容 {leaks}")


